export const bestSellers = allProducts.filter((p) => p.isBestSeller);
export const newArrivals = allProducts.filter((p) => p.isNew);
export const featuredProducts = allProducts.filter((p) => p.featured);

export function getProductBySlug(slug: string): Product | undefined {
  return allProducts.find((p) => p.slug === slug);
}

export function productsByCategory(slug: string): Product[] {
  return allProducts.filter((p) => p.category === slug);
}

export function searchProducts(query: string): Product[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return allProducts.filter((p) => {
    const haystack = [p.name, p.description, ...p.tags, p.category]
      .join(" ")
      .toLowerCase();
    return q.split(/\s+/).every((token) => haystack.includes(token));
  });
}
